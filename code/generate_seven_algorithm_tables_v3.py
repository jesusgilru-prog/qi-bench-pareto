#!/usr/bin/env python3
"""
generate_seven_algorithm_tables_v3.py — emit the LaTeX table bodies for
the unified seven-algorithm comparison, so the manuscript's numbers are
generated from unified_seven_algorithm_comparison_v3.json rather than
transcribed by hand.

Writes results/GENERATED_SEVEN_ALGO_TABLES_v3.tex.
"""
import json
from itertools import combinations
from pathlib import Path

import numpy as np

RESULTS = Path(__file__).resolve().parent.parent / 'results'
IN_JSON = RESULTS / 'unified_seven_algorithm_comparison_v3.json'
OUT_TEX = RESULTS / 'GENERATED_SEVEN_ALGO_TABLES_v3.tex'

LABEL = {'nsga2': 'NSGA-II', 'nsga3': 'NSGA-III', 'moead': 'MOEA/D',
         'sms_emoa': 'SMS-EMOA', 'rvea': 'RVEA', 'spea2': 'SPEA2',
         'age_moea2': 'AGE-MOEA-II'}
ORDER = ['nsga2', 'spea2', 'age_moea2', 'nsga3', 'sms_emoa', 'rvea', 'moead']
METRICS = ['hv', 'igd', 'spacing']
BETTER_HIGH = {'hv': True, 'igd': False, 'spacing': False}


def stars(p):
    if p < 0.01:
        return '^{**}'
    if p < 0.05:
        return '^{*}'
    return ''


def fmt_p(p):
    return '<0.001' if p < 0.001 else f'{p:.3f}'


def main():
    d = json.load(open(IN_JSON))
    S = d['summary']
    unp = d['pairwise_unpaired_mannwhitney_holm']
    pair = d['pairwise_paired_wilcoxon_holm']

    best = {}
    for m in METRICS:
        vals = {a: S[a][m]['mean'] for a in ORDER}
        best[m] = max(vals, key=vals.get) if BETTER_HIGH[m] else min(vals, key=vals.get)
    best['n_pareto'] = max(ORDER, key=lambda a: S[a]['n_pareto']['mean'])
    best['elapsed_min'] = min(ORDER, key=lambda a: S[a]['elapsed_min']['mean'])

    lines = ['% Generated by generate_seven_algorithm_tables_v3.py -- do not edit by hand.',
             '% ---- main comparison table body ----']
    for a in ORDER:
        s = S[a]
        cells = []
        for m in METRICS:
            txt = f"{s[m]['mean']:.3f} \\pm {s[m]['std']:.3f}"
            cells.append(f"$\\mathbf{{{txt}}}$" if best[m] == a else f"${txt}$")
        for m in ['n_pareto', 'elapsed_min']:
            txt = f"{s[m]['mean']:.1f} \\pm {s[m]['std']:.1f}"
            cells.append(f"$\\mathbf{{{txt}}}$" if best[m] == a else f"${txt}$")
        lines.append(f"{LABEL[a]:12s} & " + ' & '.join(cells) + r' \\')

    lines.append('% ---- Kruskal-Wallis omnibus (independent samples) ----')
    for m in METRICS:
        o = d['omnibus'][f'kruskal_{m}']
        lines.append(f"{m.upper():8s} & ${o['H']:.3f}$ & ${fmt_p(o['p'])}$ \\\\")

    lines.append('% ---- Friedman omnibus (paired) ----')
    for m in METRICS:
        o = d['omnibus'][f'friedman_{m}']
        lines.append(f"{m.upper():8s} & ${o['chi2']:.3f}$ & ${fmt_p(o['p'])}$ \\\\")

    def key(a, b):
        i, j = ORDER.index(a), ORDER.index(b)
        # keys were built in the ALGOS order of the analysis script
        algos = d['config']['algorithms']
        x, y = (a, b) if algos.index(a) < algos.index(b) else (b, a)
        return x, y

    lines.append('% ---- pairwise Mann-Whitney (independent, joint Holm over 63 tests) ----')
    for a, b in combinations(ORDER, 2):
        x, y = key(a, b)
        cells = []
        for m in METRICS:
            r = unp[f'{m}:{x}_vs_{y}']
            delta = r['cliffs_delta'] if (x, y) == (a, b) else -r['cliffs_delta']
            cells.append(f"$({fmt_p(r['p_holm'])}{stars(r['p_holm'])}, {delta:+.2f})$")
        lines.append(f"{LABEL[a]} vs.\\ {LABEL[b]} & " + ' & '.join(cells) + r' \\')

    lines.append('% ---- pairwise Wilcoxon (paired, joint Holm over 63 tests) ----')
    for a, b in combinations(ORDER, 2):
        x, y = key(a, b)
        cells = []
        for m in METRICS:
            r = pair[f'{m}:{x}_vs_{y}']
            rb = r['rank_biserial'] if (x, y) == (a, b) else -r['rank_biserial']
            cells.append(f"$({fmt_p(r['p_holm'])}{stars(r['p_holm'])}, {rb:+.2f})$")
        lines.append(f"{LABEL[a]} vs.\\ {LABEL[b]} & " + ' & '.join(cells) + r' \\')

    # agreement between designs
    agree = sum(1 for k in unp
                if unp[k]['significant_holm_005'] == pair[k]['significant_holm_005'])
    disagree = [k for k in unp
                if unp[k]['significant_holm_005'] != pair[k]['significant_holm_005']]
    n_sig_unp = sum(1 for k in unp if unp[k]['significant_holm_005'])
    n_sig_pair = sum(1 for k in pair if pair[k]['significant_holm_005'])
    rb_sig = [abs(pair[k]['rank_biserial']) for k in pair if pair[k]['significant_holm_005']]
    d_sig = [abs(unp[k]['cliffs_delta']) for k in unp if unp[k]['significant_holm_005']]

    lines += [
        '% ---- prose figures ----',
        f'% family size: {len(unp)} tests (3 metrics x 21 pairs)',
        f'% significant after joint Holm: unpaired {n_sig_unp}/{len(unp)}, '
        f'paired {n_sig_pair}/{len(pair)}',
        f'% designs agree on {agree}/{len(unp)} comparisons',
        f'% disagreements: {sorted(disagree)}',
        f'% min |delta| among significant unpaired: {min(d_sig):.2f}',
        f'% min |r_rb| among significant paired: {min(rb_sig):.2f}',
        f"% top group indistinguishable from best HV: "
        f"{d['top_group_indistinguishable_from_best_hv']}",
    ]

    OUT_TEX.write_text('\n'.join(lines) + '\n')
    print(f'Saved: {OUT_TEX}')
    print('\n'.join(lines))


if __name__ == '__main__':
    main()
